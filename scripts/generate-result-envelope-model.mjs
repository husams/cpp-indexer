import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = resolve(root, "spec/contracts/result-envelope.schema.json");
const outputPath = resolve(root, "spec/contracts/generated/result-envelope.ts");
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));

const union = (values) => values.map((value) => JSON.stringify(value)).join(" | ");
const status = union(schema.properties.status.enum);
const reasonCode = union(schema.properties.reasonCode.enum);
const diagnosticCode = union(schema.properties.diagnostics.items.properties.code.enum);
const output = `// Generated by scripts/generate-result-envelope-model.mjs; do not edit.
// Source: spec/contracts/result-envelope.schema.json

export type ResultStatus = ${status};
export type ResultReasonCode = ${reasonCode};
export type ResultDiagnosticCode = ${diagnosticCode};
export type DiagnosticSeverity = "info" | "warning" | "error";

export interface ResultDiagnostic {
  code: ResultDiagnosticCode;
  message: string;
  severity: DiagnosticSeverity;
}

export interface ResultIdentity {
  key: string;
  version: string;
}

export interface ProducerIdentity {
  name: string;
  version: string;
}

export interface PackageIdentity {
  name: string;
  version: string;
}

export interface BackendIdentity {
  name: string;
  version: string;
  kind: string;
}

export interface ResultContext {
  workspace: ResultIdentity;
  index: ResultIdentity;
  factSet: ResultIdentity;
}

export interface ArtifactReference {
  kind: string;
  id: string;
  schemaVersion: string;
  catalogVersion?: string;
  catalogHash?: string;
}

export interface ReplayMetadata {
  requestIdentity: string;
  inputRevision: string;
  deterministic: boolean;
}

export interface ResourceMetadata {
  elapsedMs: number;
  cpuMs?: number;
  bytes: number;
  peakBytes?: number;
}

export interface ResultEnvelope<TPayload> {
  envelopeVersion: 1;
  operation: string;
  status: ResultStatus;
  reasonCode: ResultReasonCode;
  diagnostics: readonly ResultDiagnostic[];
  producer: ProducerIdentity;
  package: PackageIdentity;
  backend: BackendIdentity;
  context: ResultContext;
  artifact: ArtifactReference;
  replay: ReplayMetadata;
  resources: ResourceMetadata;
  payload: TPayload;
}
`;

writeFileSync(outputPath, output);

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = resolve(root, "spec/contracts/result-envelope.schema.json");
const outputPath = resolve(root, "spec/contracts/generated/result-envelope.ts");
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));

const union = (values) => values.map((value) => JSON.stringify(value)).join(" | ");
const status = union(schema.properties.status.enum);
const exitClass = union(schema.properties.exit_class.enum);
const evidenceClass = union(schema.properties.evidence.items.properties.class.enum);
const evidenceTrust = union(schema.properties.evidence.items.properties.trust.enum);
const output = `// Generated by scripts/generate-result-envelope-model.mjs; do not edit.
// Source: spec/contracts/result-envelope.schema.json

export type ResultStatus = ${status};
export type ExitClass = ${exitClass};
export type EvidenceClass = ${evidenceClass};
export type EvidenceTrust = ${evidenceTrust};
export type DiagnosticSeverity = "info" | "warning" | "error";

export interface ResultDiagnostic {
  code: string;
  severity: DiagnosticSeverity;
  message: string;
  next_action?: string;
}

export interface ResultIdentity {
  workspace: string;
  index: string;
  fact_sets: readonly string[];
  freshness: "current" | "stale" | "unverifiable";
  source_revision: string | null;
  source_fingerprint: string | null;
}

export interface ResultProducer {
  package: string;
  version: string;
  backend: string;
  schema_version: number;
}

export interface Completeness {
  state: "complete" | "partial" | "unknown";
  truncated: boolean;
  stale: boolean;
  budget: number | null;
}

export interface ResultEvidence {
  id: string;
  class: EvidenceClass;
  trust: EvidenceTrust;
  summary: string;
  source?: string;
  children?: readonly ResultEvidence[];
}

export interface ResultArtifact {
  kind: string;
  id: string;
  schema_version: number;
  catalog_version: number;
  catalog_hash: string;
}

export interface ReplayInput {
  command: string;
  arguments: readonly string[];
}

export interface ResourceMetadata {
  elapsed_ms: number | null;
  peak_bytes: number | null;
}

export interface ResultEnvelope<TPayload> {
  protocol: "cidx.result/v1";
  operation: string;
  status: ResultStatus;
  exit_class: ExitClass;
  exit_code: number;
  result: TPayload;
  identity: ResultIdentity;
  producer: ResultProducer;
  completeness: Completeness;
  diagnostics: readonly ResultDiagnostic[];
  evidence: readonly ResultEvidence[];
  artifacts: readonly ResultArtifact[];
  replay?: ReplayInput;
  resources?: ResourceMetadata;
}
`;

writeFileSync(outputPath, output);
